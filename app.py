import joblib, pandas as pd, streamlit as st

st.set_page_config(page_title="AI-Based Employee Salary Predictor", page_icon="💼")
model = joblib.load("model/salary_model.pkl")

st.sidebar.header("Model Information")
st.sidebar.write("**Algorithm:** Linear Regression")
st.sidebar.write("**Features:** Age, Years of Experience, Education Level, Job Level, Weekly Working Hours")
st.sidebar.write("**Output:** Predicted Annual Salary")
st.sidebar.subheader("About the Project")
st.sidebar.write("Demonstrates how machine learning can be integrated with cloud computing "
                 "to provide remote access to an AI application.")

st.title("AI-Based Employee Salary Predictor")
st.subheader("Machine Learning Based Salary Estimation System")
st.write("This application estimates an employee's salary based on selected professional and "
         "demographic attributes using a Linear Regression machine learning model.")

age = st.number_input("Age", 21, 60, 30)
exp = st.slider("Years of Experience", 0, 25, 5)
edu = st.selectbox("Education Level", ["Bachelors", "Masters", "PhD"])
lvl = st.selectbox("Job Level", ["Junior", "Mid", "Senior", "Manager"])
hrs = st.slider("Weekly Working Hours", 35, 55, 40)

if st.button("Predict Salary"):
    row = pd.DataFrame([dict(age=age, years_experience=exp, education_level=edu,
                             job_level=lvl, weekly_hours=hrs)])
    s = max(0, float(model.predict(row)[0]))
    st.metric("Predicted Annual Salary", f"₹{s:,.0f}")
    st.caption("Prediction is an estimated value generated by a machine learning model and "
               "should not be considered an actual salary offer.")
